"""Pull the US-sending rows out of the World Bank's Remittance Prices Worldwide workbook
(DECISIONS.md D115, D118) into us-sends.csv, and write the summary tables in summary.md.

    uv run research/world-bank-rpw/extract.py ~/Downloads/rpw_dataset_2011_2025_q1.xlsx

The workbook comes from https://remittanceprices.worldbank.org/data-download (a browser can
fetch it; a plain request gets 403). It isn't kept in the repo: 49 MB, and the CSV holds
everything we use. Rows from Q2 2016 on; earlier quarters used a different layout.

Source: The World Bank, Remittance Prices Worldwide, available at
http://remittanceprices.worldbank.org. The World Bank doesn't endorse this use.
"""

from __future__ import annotations

import csv
import statistics
import sys
from collections import defaultdict
from pathlib import Path

from openpyxl import load_workbook

HERE = Path(__file__).resolve().parent
SHEET = "Dataset (from Q2 2016)"

# The workbook's column -> ours. cc1 is the $200 send, cc2 the $500 send.
COLUMNS = {
    "period": "period",
    "destination_code": "destination",
    "destination_name": "destination_name",
    "firm": "firm",
    "firm_type": "firm_type",
    "payment instrument": "payment_instrument",
    "access point": "access_point",
    "speed actual": "speed",
    "pickup method": "receive_method",
    "cc1 lcu fee": "fee_200",
    "cc1 lcu fx rate": "rate_200",
    "cc1 fx margin": "fx_margin_pct_200",
    "cc1 total cost %": "total_cost_pct_200",
    "cc2 lcu fee": "fee_500",
    "cc2 lcu fx rate": "rate_500",
    "cc2 fx margin": "fx_margin_pct_500",
    "cc2 total cost %": "total_cost_pct_500",
    "inter lcu bank fx": "reference_rate",
    "transparent": "transparent",
}

# The app's Tier 1 routes, for the summary.
TIER1 = {"IND": "India", "MEX": "Mexico", "PHL": "Philippines", "VNM": "Vietnam"}


def extract(xlsx: Path) -> list[dict]:
    ws = load_workbook(xlsx, read_only=True)[SHEET]
    rows = ws.iter_rows(values_only=True)
    header = list(next(rows))
    index = {name: header.index(name) for name in COLUMNS}
    source = header.index("source_code")
    out = []
    for row in rows:
        if row[source] != "USA":
            continue
        r = {ours: _clean(row[index[theirs]]) for theirs, ours in COLUMNS.items()}
        r["transparent"] = str(r["transparent"]).lower()  # "yes" until 2024, "Yes" in 2025
        out.append(r)
    out.sort(key=lambda r: (r["period"], r["destination"], r["firm"]))
    return out


def _clean(v):
    if isinstance(v, str):
        v = v.strip()
        return "" if v in ("..", "n.a.") else v
    return "" if v is None else v


def _num(v) -> float | None:
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _period_label(p: str) -> str:
    year, q = p.split("_")
    return f"Q{q[0]} {year}"


def summary(rows: list[dict]) -> str:
    latest = max(r["period"] for r in rows)
    lines = [
        "# World Bank remittance prices: sending from the US",
        "",
        "Generated by `extract.py` from the World Bank's Remittance Prices Worldwide workbook",
        f"(Q2 2016 to {_period_label(latest)}). **Research only (D115): these are survey prices",
        "from a past quarter, never shown as today's price in Compare.**",
        "",
        "Source: The World Bank, Remittance Prices Worldwide, available at",
        "http://remittanceprices.worldbank.org. The World Bank doesn't endorse this use.",
        "",
        "Total cost is the World Bank's: the fee plus the exchange-rate margin, as a share of",
        "the amount sent, for a $200 and a $500 transfer. Where a provider doesn't disclose its",
        "rate, the World Bank records a 0% margin and marks it not transparent; those rows are",
        "left out of the medians below.",
        "",
        f"## The four Tier 1 routes, {_period_label(latest)}",
        "",
    ]
    for code, name in TIER1.items():
        services = [r for r in rows if r["period"] == latest and r["destination"] == code]
        lines += [
            f"### {name} ({len(services)} services surveyed)",
            "",
            "| Provider | Type | Paid by | Arrives as | Speed | $200 total cost | $500 total cost |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in sorted(services, key=lambda r: (_num(r["total_cost_pct_500"]) or 99, r["firm"])):
            t200, t500 = _num(r["total_cost_pct_200"]), _num(r["total_cost_pct_500"])
            flag = "" if r["transparent"] == "yes" else " (rate not disclosed)"
            lines.append(
                f"| {r['firm']}{flag} | {r['firm_type']} | {r['payment_instrument']} | "
                f"{r['receive_method']} | {r['speed']} | {_pct(t200)} | {_pct(t500)} |"
            )
        lines.append("")

    lines += [
        "## Median total cost of a $200 transfer, by year",
        "",
        "| Year | " + " | ".join(TIER1.values()) + " | All US routes |",
        "|---|" + "---|" * (len(TIER1) + 1),
    ]
    by_year: dict[str, dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for r in rows:
        t = _num(r["total_cost_pct_200"])
        if t is None or r["transparent"] != "yes":
            continue
        year = r["period"].split("_")[0]
        by_year[year]["all"].append(t)
        if r["destination"] in TIER1:
            by_year[year][r["destination"]].append(t)
    for year in sorted(by_year):
        cells = [_pct(_median(by_year[year][c])) for c in TIER1] + [_pct(_median(by_year[year]["all"]))]
        lines.append(f"| {year} | " + " | ".join(cells) + " |")
    lines += [
        "",
        f"{len(rows):,} US rows in `us-sends.csv`, "
        f"{len({r['destination'] for r in rows})} receiving countries, "
        f"{len({r['period'] for r in rows})} quarters.",
        "",
    ]
    return "\n".join(lines)


def _median(xs: list[float]) -> float | None:
    return statistics.median(xs) if xs else None


def _pct(x: float | None) -> str:
    return "" if x is None else f"{x:.2f}%"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    rows = extract(Path(sys.argv[1]).expanduser())
    with (HERE / "us-sends.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(COLUMNS.values()))
        w.writeheader()
        w.writerows(rows)
    (HERE / "summary.md").write_text(summary(rows))
    print(f"{len(rows)} rows -> us-sends.csv, summary.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
